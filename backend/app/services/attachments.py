"""Receipt uploads: validation, storage on disk and metadata.

Files are stored as ``<upload_dir>/claims/<claim_id>/<random hex><ext>``. The
stored name is generated by the server, never taken from the client, so an
uploaded file name cannot escape the upload folder.
"""

from __future__ import annotations

import hashlib
import uuid
from pathlib import Path, PurePath
from typing import BinaryIO

from fastapi import status
from sqlalchemy import func, select
from sqlalchemy.orm import Session

from app.config import get_settings
from app.errors import AppError
from app.models import AuditAction, ClaimAttachment, User
from app.services import audit, claims

# Accepted content type -> (stored extension, leading "magic" bytes of a real file).
ALLOWED_TYPES: dict[str, tuple[str, tuple[bytes, ...]]] = {
    "application/pdf": (".pdf", (b"%PDF-",)),
    "image/png": (".png", (b"\x89PNG\r\n\x1a\n",)),
    "image/jpeg": (".jpg", (b"\xff\xd8\xff",)),
}


class UnsupportedFileType(AppError):
    status_code = status.HTTP_415_UNSUPPORTED_MEDIA_TYPE
    code = "unsupported_file_type"
    message = "Only PDF, PNG and JPEG receipts are accepted."


class FileTooLarge(AppError):
    status_code = status.HTTP_413_CONTENT_TOO_LARGE
    code = "file_too_large"
    message = "The file is larger than the upload limit."


class EmptyFile(AppError):
    status_code = status.HTTP_422_UNPROCESSABLE_ENTITY
    code = "empty_file"
    message = "The uploaded file is empty."


class AttachmentLimitReached(AppError):
    status_code = status.HTTP_409_CONFLICT
    code = "attachment_limit_reached"
    message = "This claim already has the maximum number of attachments."


class AttachmentNotFound(AppError):
    status_code = status.HTTP_404_NOT_FOUND
    code = "attachment_not_found"
    message = "Attachment not found."


def upload_root() -> Path:
    return get_settings().upload_dir.resolve()


def save_receipt(
    db: Session,
    user: User,
    claim_id: int,
    *,
    filename: str | None,
    content_type: str | None,
    stream: BinaryIO,
) -> ClaimAttachment:
    settings = get_settings()
    claim = claims.get_editable_claim(db, user, claim_id)

    existing = db.scalar(
        select(func.count())
        .select_from(ClaimAttachment)
        .where(ClaimAttachment.claim_id == claim.id)
    )
    if (existing or 0) >= settings.max_attachments_per_claim:
        raise AttachmentLimitReached(
            details={"max_attachments_per_claim": settings.max_attachments_per_claim}
        )

    if content_type not in ALLOWED_TYPES:
        raise UnsupportedFileType(details={"content_type": content_type})
    extension, signatures = ALLOWED_TYPES[content_type]

    data = stream.read(settings.max_upload_bytes + 1)
    if not data:
        raise EmptyFile()
    if len(data) > settings.max_upload_bytes:
        raise FileTooLarge(details={"max_upload_bytes": settings.max_upload_bytes})
    if not data.startswith(signatures):
        raise UnsupportedFileType("The file content does not match its declared type.")

    relative = PurePath("claims", str(claim.id), f"{uuid.uuid4().hex}{extension}")
    target = upload_root() / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(data)

    try:
        attachment = ClaimAttachment(
            claim_id=claim.id,
            original_name=PurePath(filename or f"receipt{extension}").name[:255],
            stored_path=relative.as_posix(),
            content_type=content_type,
            size_bytes=len(data),
            sha256=hashlib.sha256(data).hexdigest(),
            uploaded_by=user.id,
        )
        db.add(attachment)
        db.flush()
        claim.updated_by = user.id
        audit.record(
            db,
            entity_type=claims.ENTITY_TYPE,
            entity_id=claim.id,
            action=AuditAction.UPDATED,
            changes={
                f"attachments.{attachment.id}": {
                    "old": None,
                    "new": {
                        "original_name": attachment.original_name,
                        "content_type": attachment.content_type,
                        "size_bytes": attachment.size_bytes,
                        "sha256": attachment.sha256,
                    },
                }
            },
            actor_id=user.id,
        )
        db.commit()
    except Exception:
        db.rollback()
        target.unlink(missing_ok=True)
        raise

    db.refresh(attachment)
    return attachment


def get_receipt(
    db: Session, user: User, claim_id: int, attachment_id: int
) -> tuple[ClaimAttachment, Path]:
    """The attachment and its file path, if the caller may see the claim."""
    claims.get_visible_claim(db, user, claim_id)
    attachment = db.scalar(
        select(ClaimAttachment).where(
            ClaimAttachment.id == attachment_id, ClaimAttachment.claim_id == claim_id
        )
    )
    if attachment is None:
        raise AttachmentNotFound()

    root = upload_root()
    path = (root / attachment.stored_path).resolve()
    if not path.is_relative_to(root) or not path.is_file():
        raise AttachmentNotFound("The receipt file is missing from storage.")
    return attachment, path
